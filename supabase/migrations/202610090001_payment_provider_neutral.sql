-- STORES専用だった契約台帳を、既存記録を保持したままPayPalでも使えるようにする。
-- テーブル名と旧カラムは後方互換のため残し、新規処理はpayment_* / external_*を使用する。

alter table public.stores_subscriptions
  add column if not exists payment_provider text,
  add column if not exists external_reference_id text,
  add column if not exists external_product_id text,
  add column if not exists external_plan_id text,
  add column if not exists external_subscription_id text,
  add column if not exists external_customer_id text;

update public.stores_subscriptions
set
  payment_provider = coalesce(payment_provider, 'stores'),
  external_reference_id = coalesce(external_reference_id, stores_subscription_id, stores_order_id),
  external_product_id = coalesce(external_product_id, stores_item_id),
  external_subscription_id = coalesce(external_subscription_id, stores_subscription_id),
  external_customer_id = coalesce(external_customer_id, stores_customer_id)
where
  payment_provider is null
  or external_reference_id is null
  or external_product_id is null
  or external_subscription_id is null
  or external_customer_id is null;

alter table public.stores_subscriptions
  alter column payment_provider set default 'stores',
  alter column payment_provider set not null,
  alter column stores_item_id drop not null;

alter table public.stores_subscriptions
  drop constraint if exists stores_subscriptions_payment_provider_check;

alter table public.stores_subscriptions
  add constraint stores_subscriptions_payment_provider_check
  check (payment_provider in ('paypal', 'stores', 'manual'));

create unique index if not exists stores_subscriptions_provider_reference_unique_idx
  on public.stores_subscriptions (payment_provider, external_reference_id)
  where external_reference_id is not null;

create unique index if not exists stores_subscriptions_provider_subscription_unique_idx
  on public.stores_subscriptions (payment_provider, external_subscription_id)
  where external_subscription_id is not null;

comment on table public.stores_subscriptions is
  '決済サービスを問わず定期購入と会員プランの対応を保持するサーバー専用台帳。旧STORESカラムは移行互換用。カード情報は保存しない';

comment on column public.stores_subscriptions.payment_provider is
  '決済サービス識別子: paypal, stores, manual';

comment on column public.stores_subscriptions.external_reference_id is
  '管理画面で照合する決済サービス側の注文番号または契約ID';

-- PayPal Webhook自動連携を後から安全に追加できるよう、重複受信防止用の共通履歴を用意する。
-- この移行だけではWebhookを受信・処理しない。
create table if not exists public.payment_webhook_events (
  id bigint generated by default as identity primary key,
  payment_provider text not null check (payment_provider in ('paypal', 'stores')),
  external_event_id text not null,
  event_type text not null,
  processing_status text not null default 'received'
    check (processing_status in ('received', 'processed', 'ignored', 'failed')),
  received_at timestamptz not null default now(),
  processed_at timestamptz,
  source_payload jsonb not null default '{}'::jsonb,
  error_message text,
  unique (payment_provider, external_event_id)
);

alter table public.payment_webhook_events enable row level security;
revoke all on public.payment_webhook_events from anon, authenticated;
grant select, insert, update, delete on table public.payment_webhook_events to service_role;
grant usage, select on sequence public.payment_webhook_events_id_seq to service_role;

comment on table public.payment_webhook_events is
  '決済サービス通知の重複処理防止と障害確認に使うサーバー専用履歴。受信処理は別段階で有効化する';
